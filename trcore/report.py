"""Deterministic JSON/Markdown report builders and a safe output writer.

Reports are derived artifacts, not sources of truth. They carry no timestamps
or absolute paths, so two runs over the same inputs produce identical bytes.
"""
from __future__ import annotations

import json
import os
from typing import Dict, List, Optional

from . import TOOL_NAME, __version__
from .stc import layout as L
from .stc.document import StageDocument

STAGE_SCHEMA = "trcore.stage_report/1"
MATRIX_SCHEMA = "trcore.validation_matrix/1"


def tool_id() -> str:
    return f"{TOOL_NAME} {__version__}"


def _strip_internal(span: dict) -> dict:
    return {k: v for k, v in span.items() if not k.startswith("_")}


def stage_report(doc: StageDocument, stage_key: Optional[str], source_path: Optional[str],
                 also_known_as: Optional[List[str]] = None) -> dict:
    return {
        "schema": STAGE_SCHEMA,
        "tool": tool_id(),
        "notice": "Labels are research hypotheses (see evidence IDs); nothing here is confirmed in-game.",
        "stage_key": stage_key,
        "identical_content_stage_keys": sorted(also_known_as or []),
        "source_path": source_path,
        "container": doc.container,
        "source_size": len(doc.source),
        "source_sha256": doc.source_sha256,
        "lz10": doc.lz10_info,
        "decoded_size": len(doc.decoded) if doc.decoded is not None else None,
        "decoded_sha256": doc.decoded_sha256,
        "layout_variant": doc.layout_variant,
        "facts": doc.facts(),
        "checks": doc.checks,
        "diagnostics": list(doc.diagnostics),
        "header": doc.header,
        "start": doc.start,
        "pools": doc.pools,
        "groups": doc.groups,
        "strings": doc.strings,
        "spans": [_strip_internal(s) for s in doc.spans],
        "coverage": doc.coverage,
        "evidence": {k: L.EVIDENCE[k] for k in sorted(_evidence_ids(doc))},
    }


def _evidence_ids(doc: StageDocument):
    ids = set()
    for v in doc.header.values():
        if v.get("evidence"):
            ids.add(v["evidence"])
    for s in doc.spans:
        if s.get("evidence"):
            ids.add(s["evidence"])
    for d in doc.diagnostics:
        if d.get("evidence"):
            ids.add(d["evidence"])
    return ids


def report_filename(stage_key: Optional[str], decoded_sha256: Optional[str], source_sha256: str) -> str:
    key = stage_key or "unkeyed"
    sha = (decoded_sha256 or source_sha256)[:8]
    safe = "".join(ch if ch.isalnum() or ch in "-_." else "_" for ch in key)
    return f"{safe}.{sha}.json"


def validation_matrix(entries: List[dict]) -> dict:
    """entries: [{stage_key, also, doc_checks, variant, diag_codes}] — one per UNIQUE decoded content."""
    checks: Dict[str, Dict[str, int]] = {}
    failing: Dict[str, List[str]] = {}
    variants: Dict[str, List[str]] = {}
    diag_counts: Dict[str, int] = {}
    for e in entries:
        variants.setdefault(e["variant"], []).append(e["stage_key"])
        for name, status in e["checks"].items():
            checks.setdefault(name, {"pass": 0, "fail": 0, "n/a": 0})[status] += 1
            if status == "fail":
                failing.setdefault(name, []).append(e["stage_key"])
        for code in e["diag_codes"]:
            diag_counts[code] = diag_counts.get(code, 0) + 1
    return {
        "schema": MATRIX_SCHEMA,
        "tool": tool_id(),
        "unique_stage_contents": len(entries),
        "checks": checks,
        "failing_stage_keys": {k: sorted(v) for k, v in sorted(failing.items())},
        "layout_variants": {k: sorted(v) for k, v in sorted(variants.items())},
        "diagnostic_counts": dict(sorted(diag_counts.items())),
    }


def matrix_markdown(matrix: dict, index_summary: Optional[dict] = None) -> str:
    lines = ["# trcore validation matrix", "",
             f"Generated by `{matrix['tool']}`. Derived artifact; regenerate with "
             "`py -3 -m trcore validate`. Each row counts unique decoded stage contents "
             f"({matrix['unique_stage_contents']}); byte-identical stages under different keys count once.", ""]
    if index_summary:
        lines += [f"Corpus: {index_summary['files']} files, {index_summary['pairs']} stage/type pairs, "
                  f"pair status {index_summary['pairs_by_status']}, index errors {index_summary['error_count']}.", ""]
    lines += ["| Check | pass | fail | n/a | failing stage keys |", "|---|---:|---:|---:|---|"]
    for name, c in matrix["checks"].items():
        fails = ", ".join(matrix["failing_stage_keys"].get(name, [])) or "—"
        lines.append(f"| `{name}` | {c['pass']} | {c['fail']} | {c['n/a']} | {fails} |")
    lines += ["", "Layout variants: " + "; ".join(f"`{k}` × {len(v)}" for k, v in matrix["layout_variants"].items()),
              "", "Diagnostic codes (files reporting each): " +
              ", ".join(f"`{k}` {v}" for k, v in matrix["diagnostic_counts"].items()), ""]
    return "\n".join(lines)


def dumps(obj) -> str:
    return json.dumps(obj, indent=1, ensure_ascii=True) + "\n"


class OutputRefused(ValueError):
    pass


class OutputWriter:
    """Writes generated files under one output directory.

    * refuses an output directory inside a protected input directory;
    * writes atomically (temp file + os.replace);
    * records whether each file was created, unchanged, or replaced.
    """

    def __init__(self, out_dir: str, protected_dirs: List[str]):
        out_abs = os.path.abspath(out_dir)
        for p in protected_dirs:
            p_abs = os.path.abspath(p)
            if out_abs == p_abs or out_abs.startswith(p_abs + os.sep):
                raise OutputRefused(f"refusing to write generated output inside input directory {p}")
        self.out_dir = out_abs
        self.log: List[dict] = []

    def write_text(self, relpath: str, text: str) -> str:
        path = os.path.join(self.out_dir, *relpath.split("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        data = text.encode("utf-8")
        status = "created"
        if os.path.exists(path):
            with open(path, "rb") as fh:
                status = "unchanged" if fh.read() == data else "replaced"
        if status != "unchanged":
            tmp = path + ".tmp"
            with open(tmp, "wb") as fh:
                fh.write(data)
            os.replace(tmp, path)
        self.log.append({"path": relpath, "status": status, "bytes": len(data)})
        return path
